
    CREATE TABLE IF NOT EXISTS admins (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      email TEXT UNIQUE NOT NULL,
      password_hash TEXT NOT NULL,
      name TEXT NOT NULL,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    )
  ;


    CREATE TABLE IF NOT EXISTS clients (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      full_name TEXT NOT NULL,
      email TEXT NOT NULL,
      phone TEXT NOT NULL,
      country TEXT,
      doc_type TEXT,
      doc_number TEXT,
      language TEXT DEFAULT 'es',
      notes TEXT,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    )
  ;


    CREATE TABLE IF NOT EXISTS services (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      description TEXT,
      duration_minutes INTEGER DEFAULT 30,
      is_active BOOLEAN DEFAULT true,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    )
  ;


    CREATE TABLE IF NOT EXISTS time_slots (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      date DATE NOT NULL,
      time TIME NOT NULL,
      service_id INTEGER NOT NULL,
      is_booked BOOLEAN DEFAULT false,
      client_id INTEGER,
      status TEXT DEFAULT 'available' CHECK(status IN ('available', 'booked', 'cancelled')),
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      FOREIGN KEY (service_id) REFERENCES services(id),
      FOREIGN KEY (client_id) REFERENCES clients(id)
    )
  ;


    CREATE TABLE IF NOT EXISTS appointments (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      client_id INTEGER NOT NULL,
      slot_id INTEGER NOT NULL,
      status TEXT DEFAULT 'pending' CHECK(status IN ('pending', 'confirmed', 'in_progress', 'completed', 'cancelled')),
      duration_minutes INTEGER CHECK(duration_minutes IS NULL OR duration_minutes > 0),
      admin_notes TEXT,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      FOREIGN KEY (client_id) REFERENCES clients(id),
      FOREIGN KEY (slot_id) REFERENCES time_slots(id)
    )
  ;


    CREATE TABLE IF NOT EXISTS appointment_services (
      appointment_id INTEGER NOT NULL REFERENCES appointments(id) ON DELETE CASCADE,
      service_id INTEGER NOT NULL REFERENCES services(id),
      duration_minutes INTEGER NOT NULL CHECK(duration_minutes > 0),
      position INTEGER NOT NULL DEFAULT 0,
      PRIMARY KEY (appointment_id, service_id)
    )
  ;

CREATE INDEX IF NOT EXISTS appointment_services_service_idx ON appointment_services(service_id);


    CREATE TABLE IF NOT EXISTS notifications (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      appointment_id INTEGER,
      type TEXT NOT NULL,
      channel TEXT NOT NULL,
      to_email TEXT,
      to_phone TEXT,
      sent BOOLEAN DEFAULT false,
      error TEXT,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    )
  ;

CREATE UNIQUE INDEX IF NOT EXISTS slots_unique ON time_slots(date,time,service_id);

CREATE UNIQUE INDEX IF NOT EXISTS services_name_unique ON services(name);

CREATE UNIQUE INDEX IF NOT EXISTS active_appointment_unique ON appointments(slot_id) WHERE status <> 'cancelled';

