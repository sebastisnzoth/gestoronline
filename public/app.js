document.getElementById('regForm').addEventListener('submit', async (e) => {
  e.preventDefault();
  if(!currentSlot||!updateProceed())return;
  
  const payload = {
    full_name: document.getElementById('fullName').value,
    email: document.getElementById('email').value,
    phone: document.getElementById('phone').value,
    country: document.getElementById('country').value,
    doc_type: document.getElementById('docType').value,
    doc_number: document.getElementById('docNumber').value,
    language: currentLang,
    notes: bookingLabels().map((label,i)=>label+': '+String(requestDraft[i]||'').trim()).join('\n')+'\n'+document.getElementById('notes').value
  };
  
  // Show loading state
  const submitBtn = e.target.querySelector('button[type="submit"]');
  const originalText = submitBtn.innerHTML;
  submitBtn.innerHTML = '<div class="animate-spin rounded-full h-5 w-5 border-b-2 border-white mx-auto"></div>';
  submitBtn.disabled = true;
  
  try {
    // Register/get client
    const regRes = await fetch('/api/register', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload)
    });
    const regData = await regRes.json();
    
    if (!regData.success) throw new Error(regData.error);
    
    clientId = regData.client_id;
    
    // Book appointment
    const bookRes = await fetch('/api/book', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ client_id: clientId, registration_token: regData.registration_token, slot_id: currentSlot.slot_id })
    });
    const bookData = await bookRes.json();
    
    if (!bookData.success) throw new Error(bookData.error);
    
    // Show confirmation
    hideSteps();
    document.getElementById('confirmation').classList.remove('hidden');
    document.getElementById('confirmDetails').innerHTML = `
      <strong>Servicio:</strong> ${escapeHtml(currentService?.name || 'N/A')}<br>
      <strong>Fecha:</strong> ${currentSlot.date}<br>
      <strong>Hora:</strong> ${currentSlot.time}<br>
      <strong>Turno N°:</strong> ${bookData.appointment_id}
    `;
    
  } catch (err) {
    alert(err.message || 'Error al registrar el turno. Intente nuevamente.');
    submitBtn.innerHTML = originalText;
    submitBtn.disabled = false;
  }
});

