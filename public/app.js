let currentLang = 'es';
let currentService = null;
let currentSlot = null;
let clientId = null;

// ===== i18n Functions =====
function changeLang(lang) {
  currentLang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[lang] && translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });
  // Re-render services with new language
  loadServices();
}

async function loadServices() {
  try {
    const res = await fetch('/api/services');
    const services = await res.json();
    const grid = document.getElementById('serviceGrid');
    grid.innerHTML = '';
    
    services.forEach(s => {
      const card = document.createElement('div');
      card.className = 'border-2 border-gray-200 rounded-lg p-4 cursor-pointer hover:border-primary transition';
      card.onclick = () => selectService(s.id);
      card.id = `svc-${s.id}`;
      card.innerHTML = `
        <h4 class="font-semibold text-gray-900">${s.name}</h4>
        <p class="text-sm text-gray-500 mt-1">${s.description || ''}</p>
        <p class="text-xs text-gray-400 mt-2">⏱ ${s.duration_minutes} min</p>
      `;
      grid.appendChild(card);
    });
  } catch (e) {
    console.error('Error cargando servicios:', e);
  }
}

function selectService(id) {
  // Find service name from loaded list
  const card = document.getElementById(`svc-${id}`);
  currentService = { id, name: card.querySelector('h4').textContent };
  document.querySelectorAll('#serviceGrid > div').forEach(el => {
    el.classList.remove('border-primary', 'bg-indigo-50');
    el.classList.add('border-gray-200');
  });
  card.classList.add('border-primary', 'bg-indigo-50');
  card.classList.remove('border-gray-200');
  document.getElementById('btnStep1').classList.remove('hidden');
}

async function loadSlots(date, container) {
  if (!currentService || !date || !container) return;
  
  container.innerHTML = '<div class="col-span-full text-center py-8"><div class="animate-spin rounded-full h-8 w-8 border-b-2 border-primary mx-auto"></div><p class="mt-2 text-gray-500">Cargando horarios...</p></div>';
  
  try {
    const res = await fetch(`/api/slots?date=${date}&service_id=${currentService.id}`);
    const slots = await res.json();
    
    container.innerHTML = '';
    const today = new Date().toISOString().split('T')[0];
    
    slots.forEach(slot => {
      const isToday = slot.date === today;
      const btn = document.createElement('button');
      btn.className = `slot-btn border-2 rounded-lg p-3 text-center transition ${slot.available ? 'hover:border-primary hover:bg-indigo-50' : 'disabled'}`;
      btn.innerHTML = `
        <div class="text-xs font-medium ${isToday ? 'text-primary' : 'text-gray-500'}">${isToday ? 'Hoy' : ''}</div>
        <div class="font-semibold ${slot.available ? 'text-gray-900' : 'text-gray-400'}">${slot.time}</div>
      `;
      
      if (slot.available) {
        btn.onclick = () => selectSlot(slot, btn);
      }
      
      container.appendChild(btn);
    });
  } catch (e) {
    container.innerHTML = '<p class="col-span-full text-red-500 text-center">Error al cargar horarios</p>';
  }
}

function selectSlot(slot, btn) {
  document.querySelectorAll('.slot-btn').forEach(el => el.classList.remove('active'));
  btn.classList.add('active');
  currentSlot = slot;
  document.getElementById('btnStep2').classList.remove('hidden');
}

function nextStep(step) {
  [1, 2, 3].forEach(n => {
    document.getElementById(`step${n}`).classList.toggle('step-hidden', n !== step);
    const ind = document.getElementById(`stepInd${n}`);
    ind.classList.toggle('bg-primary', n <= step);
    ind.classList.toggle('bg-gray-200', n > step);
    ind.classList.toggle('text-white', n <= step);
    ind.classList.toggle('text-gray-500', n > step);
  });
  document.getElementById('line1').classList.toggle('bg-primary', step > 1);
  document.getElementById('line2').classList.toggle('bg-primary', step > 2);
  
  if (step === 2) showDateSelector();
  if (step === 3) {
    // Check if client exists
    const email = document.getElementById('email')?.value;
    if (email) checkExistingClient(email);
  }
}

function prevStep(step) {
  nextStep(step);
}

function showDateSelector() {
  const container = document.getElementById('slotsContainer');
  container.innerHTML = `
    <div class="mb-4">
      <label for="datePicker" class="block text-sm font-medium text-gray-700 mb-1">${t('dateLabel')}</label>
      <input type="date" id="datePicker" min="${new Date().toISOString().split('T')[0]}" 
             class="w-full p-3 border border-gray-300 rounded-lg focus:ring-2 focus:ring-blue-500 focus:border-transparent">
    </div>
    <div id="dateError" class="text-red-600 text-sm mt-2 hidden"></div>
    <div id="slotsGrid" class="mt-4 grid grid-cols-2 sm:grid-cols-3 gap-2"></div>
  `;
  document.getElementById('datePicker').addEventListener('change', (e) => {
    const selectedDate = e.target.value;
    const err = document.getElementById('dateError');
    err.classList.add('hidden');
    const grid = document.getElementById('slotsGrid');
    grid.innerHTML = '';
    
    const day = new Date(selectedDate + 'T12:00:00').getDay();
    if (day === 0 || day === 6) {
      err.textContent = t('weekendError');
      err.classList.remove('hidden');
      return;
    }
    
    loadSlots(selectedDate, grid);
  });
}

